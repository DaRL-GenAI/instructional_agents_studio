#!/usr/bin/env node
// Prebuilt ESM bundles in js/vendor/ (committed; the app has no runtime build step). Run after changing the
// versions in package.json: `node scripts/vendor.mjs`. The entries are in scripts/vendor/.
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bundles = { codemirror: 'codemirror.entry.js', docconv: 'docconv.entry.js' };
for (const [name, entry] of Object.entries(bundles)) {
  const r = await build({
    entryPoints: [path.join(root, 'scripts/vendor', entry)], outfile: path.join(root, 'js/vendor', `${name}.js`),
    bundle: true, format: 'esm', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' }, metafile: true, logLevel: 'warning',
    banner: { js: `// ${name}.js: generated by scripts/vendor.mjs, do not edit.` },
  });
  const bytes = Object.values(r.metafile.outputs)[0].bytes;
  console.log(`js/vendor/${name}.js ${(bytes / 1024).toFixed(0)} KB`);
}
